import { apiOrigin, expect, signIn, test } from '../fixtures/real-api'

test('persists a profile update and signs in using the changed password', async ({ page, request, accounts }) => {
  const account = await accounts.create()
  await signIn(page, account)
  await page.goto('/settings')
  await page.getByLabel('Name', { exact: true }).fill('Updated Journal Reader')
  await page.getByRole('button', { name: 'Save profile', exact: true }).click()
  await expect(page.getByText('Profile updated successfully!', { exact: true })).toBeVisible()
  await page.goto('/account')
  await page.reload()
  await expect(page.getByRole('link', { name: 'Updated Journal Reader', exact: true })).toBeVisible()
  await page.goto('/settings')
  await page.getByLabel('Current password', { exact: true }).fill(account.password)
  await page.getByLabel('New password', { exact: true }).fill('changed-password-123')
  await page.getByLabel('Confirm new password', { exact: true }).fill('changed-password-123')
  await page.getByRole('button', { name: 'Update password', exact: true }).click()
  await expect(page.getByText('Password updated successfully!', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Current password', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect((await request.post(`${apiOrigin}/auth/login`, { data: { email: account.email, password: account.password } })).status()).toBe(401)
  await signIn(page, { ...account, password: 'changed-password-123' })
  await page.goto('/account')
  await page.reload()
  await expect(page.getByText(account.email, { exact: true })).toBeVisible()
})
