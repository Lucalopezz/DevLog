import { apiOrigin, expect, seedProject, signIn, test } from '../fixtures/real-api'

test('creates a project and linked entry, edits its content, and reloads persisted values', async ({ page, accounts }) => {
  const account = await accounts.create()
  await signIn(page, account)
  await page.goto('/projects')
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: 'New project', exact: true })
  await dialog.getByLabel('Name', { exact: true }).fill('Browser project')
  await dialog.getByLabel('Description', { exact: true }).fill('Created through the real UI.')
  const created = page.waitForResponse((response) => response.url() === `${apiOrigin}/project` && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: 'Create project', exact: true }).click()
  const response = await created
  expect(response.status()).toBe(201)
  const project = await response.json() as { id: string }
  await expect(dialog).toBeHidden()
  await page.getByRole('link', { name: /Browser project/ }).click()
  await expect(page).toHaveURL(new RegExp(`/projects/${project.id}$`))

  await page.getByRole('tab', { name: 'Technical entries', exact: true }).click()
  await page.getByRole('button', { name: 'New entry', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'New technical entry', exact: true })
  await dialog.getByLabel('Title', { exact: true }).fill('Persist the investigation')
  await dialog.getByLabel('Context', { exact: true }).fill('An API response changed after a deployment.')
  await dialog.getByRole('button', { name: 'Create entry', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.getByRole('link', { name: /Persist the investigation/ }).click()
  await page.getByRole('button', { name: 'Edit entry', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Edit technical entry', exact: true })
  await dialog.getByLabel('Title', { exact: true }).fill('Persisted investigation title')
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Persisted investigation title', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit conclusion', exact: true }).click()
  await page.getByLabel('Conclusion', { exact: true }).fill('Keep the API and browser contracts aligned.')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Keep the API and browser contracts aligned.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Persisted investigation title', exact: true })).toBeVisible()
  await expect(page.getByText('Keep the API and browser contracts aligned.', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'View project', exact: true }).click()
  const overview = page.getByRole('tabpanel', { name: 'Overview', exact: true })
  await expect(overview.getByText('Technical entries', { exact: true }).locator('..')).toContainText('1')
  await page.getByRole('tab', { name: 'Technical entries', exact: true }).click()
  await expect(page.getByRole('link', { name: /Persisted investigation title/ })).toBeVisible()
})

test('edits, archives, restores, and deletes a project through its settings', async ({ page, request, accounts }) => {
  const account = await accounts.create()
  const project = await seedProject(request, account)
  await signIn(page, account)
  await page.goto(`/projects/${project.id}`)
  await page.getByRole('tab', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Edit project', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Edit project', exact: true })
  await dialog.getByLabel('Name', { exact: true }).fill('Renamed persistent project')
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Renamed persistent project', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Renamed persistent project', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Archive project', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Archive project', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Restore project', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Edit project', exact: true })).toBeDisabled()
  await page.reload()
  await page.getByRole('tab', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Restore project', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Restore project', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit project', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Delete project', exact: true }).click()
  const confirmation = page.getByRole('alertdialog')
  await confirmation.getByRole('textbox', { name: /Type Renamed persistent project to confirm/ }).fill('Renamed persistent project')
  await confirmation.getByRole('button', { name: 'Delete permanently', exact: true }).click()
  await expect(page).toHaveURL(/\/projects$/)
  await page.goto(`/projects/${project.id}`)
  await expect(page.getByRole('heading', { name: 'Project not found', exact: true })).toBeVisible()
})
